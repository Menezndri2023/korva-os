#!/usr/bin/env bash
#
# Replaces the Atlas password inside MONGODB_URI in ~/korva-os/.env.production, restarts the
# API container against it, and rolls back automatically if the API does not come up.
#
# Run ON THE SERVER:  ~/ops/rotate-mongo-password.sh
#
# ORDER MATTERS. Change the password in Atlas FIRST (Database Access -> korva-app -> Edit
# Password -> Autogenerate -> Copy), because the running API holds an authenticated connection
# and keeps working on the old credential until it reconnects — so the moment you rotate in
# Atlas you are on borrowed time, and this script is what closes the gap.
#
# The password is read with `read -s`: never passed as an argument, never printed, never left in
# shell history. It is percent-encoded before going into the URI — Atlas autogenerated passwords
# can contain characters that would otherwise terminate the URI early and produce an
# authentication error that looks nothing like its cause.
#
set -euo pipefail
umask 077

ENV_FILE="${KORVA_ENV_FILE:-$HOME/korva-os/.env.production}"
COMPOSE_DIR="${KORVA_COMPOSE_DIR:-$HOME/korva-os}"
COMPOSE=(docker compose -f docker-compose.prod.yml --env-file .env.production)

# The health check runs INSIDE the api container, with node's own fetch. No app service in
# docker-compose.prod.yml publishes a host port — only Caddy binds one — so a curl from the host
# to 127.0.0.1:4000 can never connect, and a check written that way would report failure after
# every rotation, including the successful ones, and then roll back a change that had worked.
# Going through Caddy would work but would make this depend on public DNS and TLS to answer a
# question about a container.
api_healthy() {
  "${COMPOSE[@]}" exec -T api node -e '
    fetch("http://127.0.0.1:4000/api/v1/health")
      .then((r) => process.exit(r.ok ? 0 : 1))
      .catch(() => process.exit(1));
  ' >/dev/null 2>&1
}

log() { printf '%s %s\n' "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$*"; }

[[ -w "$ENV_FILE" ]] || { log "FATAL: cannot write $ENV_FILE"; exit 1; }

grep -qE '^MONGODB_URI=' "$ENV_FILE" || { log "FATAL: no MONGODB_URI in $ENV_FILE"; exit 1; }

read -rsp 'New Atlas password for korva-app (not echoed): ' NEW_PASSWORD
echo
[[ -n "$NEW_PASSWORD" ]] || { log "FATAL: empty password, nothing done"; exit 1; }

BACKUP="$ENV_FILE.bak-$(date -u +%Y%m%dT%H%M%SZ)"
cp -p "$ENV_FILE" "$BACKUP"
chmod 600 "$BACKUP"
log "current env saved to $(basename "$BACKUP")"

# Rewrite in Python rather than sed: the password must be percent-encoded, and a raw sed
# substitution would also break on any `/`, `&` or `#` the new password happens to contain.
NEW_PASSWORD="$NEW_PASSWORD" ENV_FILE="$ENV_FILE" python3 <<'PY'
import os, pathlib, re, urllib.parse

path = pathlib.Path(os.environ["ENV_FILE"])
encoded = urllib.parse.quote(os.environ["NEW_PASSWORD"], safe="")

# Matches mongodb+srv://<user>:<password>@<rest>, replacing only the password group.
pattern = re.compile(r'^(MONGODB_URI=mongodb(?:\+srv)?://[^:@/]+:)([^@]*)(@.*)$', re.MULTILINE)

text = path.read_text()
new_text, count = pattern.subn(lambda m: m.group(1) + encoded + m.group(3), text)
if count != 1:
    raise SystemExit(
        f"refusing to write: expected exactly 1 MONGODB_URI with a password, matched {count}"
    )
path.write_text(new_text)
PY

chmod 600 "$ENV_FILE"
log "MONGODB_URI rewritten"

log "restarting the api container"
cd "$COMPOSE_DIR"
"${COMPOSE[@]}" up -d --force-recreate api

log "waiting for the api to answer"
for i in $(seq 1 30); do
  if api_healthy; then
    log "api healthy after ${i} attempt(s) — rotation complete"
    log "the old env file is still at $(basename "$BACKUP"); delete it once you are satisfied"
    exit 0
  fi
  sleep 3
done

# Rollback rather than leave production down: a wrong password here means the API cannot reach
# Mongo at all, and the previous credential is still valid in Atlas only if you have not yet
# rotated it there. Either way, restoring the old file and recreating the container returns the
# system to the state this script found it in.
log "FATAL: api did not become healthy — rolling back to $(basename "$BACKUP")"
cp -p "$BACKUP" "$ENV_FILE"
chmod 600 "$ENV_FILE"
"${COMPOSE[@]}" up -d --force-recreate api
log "rolled back. Check: docker compose -f docker-compose.prod.yml logs --tail=50 api"
exit 1
